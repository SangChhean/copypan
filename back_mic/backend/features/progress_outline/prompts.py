# ── 组装辅助 ────────────────────────────────────────────────────


def _norm_title(value: str, *, default: str) -> str:
    return (value or "").strip() or default


def _segment_group_header(group_title: str, group_burden: str) -> str:
    return f"""\
【二、本组定向】
本组主题：{_norm_title(group_title, default="（未命名主题）")}
本组负担说明：{_norm_title(group_burden, default="（无）")}"""


def _segment_entry_term_header(term: str, group_title: str, group_burden: str) -> str:
    return f"""\
【二、本组定向】
纲目主题（词条）：{_norm_title(term, default="（未命名词条）")}
本组主题：{_norm_title(group_title, default="（未命名主题）")}
本组负担说明：{_norm_title(group_burden, default="（无）")}"""


def _segment_material(content: str) -> str:
    return f"""\
【五、参考材料】（只可从此段逐字选材）
{content.strip()}"""


def _join_prompt_sections(*sections: str) -> str:
    return _BLOCK_SEP.join(s.strip() for s in sections if s.strip())


def build_pano_segment_prompt(
    *,
    group_title: str,
    group_burden: str,
    content: str,
) -> str:
    """进展75系列：单组分段纲目 prompt（五段合并为一条）。"""
    return _join_prompt_sections(
        _SEGMENT_ROLE_PANO,
        _segment_group_header(group_title, group_burden),
        _SEGMENT_GROUP_GUIDE,
        _SEGMENT_RULES,
        _segment_material(content),
    )


def build_entry_segment_prompt(
    *,
    term: str,
    group_title: str,
    group_burden: str,
    content: str,
) -> str:
    """新增词条：单组分段纲目 prompt（五段合并为一条）。"""
    return _join_prompt_sections(
        _SEGMENT_ROLE_ENTRY,
        _segment_entry_term_header(term, group_title, group_burden),
        _SEGMENT_GROUP_GUIDE,
        _SEGMENT_RULES,
        _segment_material(content),
    )


