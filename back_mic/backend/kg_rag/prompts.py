# -*- coding: utf-8 -*-
"""Prompt 模板：Step 1 概念抽取、Step 2 骨架精选、Step 5 生成、Query 改写。"""

# ---------------------------------------------------------------------------
# Step 1 概念抽取
# 用途：从用户 Query 中抽取 1～3 个核心神学概念词
# 占位符：{query}
# 输出：严格 JSON 数组，如 ["得胜者", "千年国"]
# ---------------------------------------------------------------------------
STEP1_CONCEPT_EXTRACTION = """你是一位熟悉圣经与神学的概念分析专家。

## 输入
用户的查询问题：
{query}

## 任务
从上述查询中抽取 1～3 个核心神学概念词。

## 规则
1. 只提取名词性的概念词（如「得胜者」「救恩」「生命树」），不提取动词或形容词。
2. 优先提取专有神学术语，而非泛泛的普通词汇。
3. 概念之间不应有包含关系（若已提取「神圣三一」，就不要再单独提取「父」）。
4. 上限 3 个，宁少勿多——若查询很聚焦只涉及 1 个概念，就只输出 1 个。

## 输出格式
严格输出一个 JSON 数组，不要任何其他文字、标点或说明。例如：
["得胜者", "千年国"]
"""

# ---------------------------------------------------------------------------
# Step 2 骨架邻居精选评分
# 用途：给定核心概念及其图谱邻居列表，对每个邻居打与当前查询的相关度分数
# 占位符：{query}、{concept_name}、{neighbors_json}
# 输出：严格 JSON 数组，如 [{"name": "道成肉身", "score": 0.950}, ...]
# ---------------------------------------------------------------------------
STEP2_SKELETON_SCORING = """你是一位神学概念关系分析专家。

## 输入
1. 用户的查询问题：{query}
2. 核心概念名称：{concept_name}
3. 该概念在图谱中的邻居列表（每项含 name 与 relation_type）：
{neighbors_json}

## 任务
对上述每一个邻居概念，判断它与**用户查询**（不只是核心概念本身）的相关度，打 0.000～1.000 的分数。

## 评分标准
- 1.0：该邻居概念是回答此查询不可或缺的
- 0.7～0.9：高度相关，能提供重要补充视角
- 0.4～0.6：有一定关联但非核心
- 0.0～0.3：与此查询关系不大

## 输出格式
严格输出一个 JSON 数组，每项为 {{"name": "概念名", "score": 分数}}，不要任何其他文字。例如：
[{"name": "道成肉身", "score": 0.950}, {"name": "复活", "score": 0.850}]
"""

# ---------------------------------------------------------------------------
# 路2 Dense 检索用：查询改写
# 用途：将用户自然语言查询改写为更适合向量语义检索的陈述句
# 占位符：{query}
# 输出：纯文本改写结果，不要 JSON 包装
# ---------------------------------------------------------------------------
QUERY_REWRITE = """你是一位搜索查询优化专家。

## 输入
用户的查询问题：{query}

## 任务
将上述查询改写为 1～2 句陈述句，保留核心语义但去掉疑问词，适合用于语义相似度搜索。

## 规则
1. 保持中文。
2. 不要添加原查询中没有的新概念。
3. 不要解释，直接输出改写后的句子。

## 输出
直接输出改写后的句子，不要 JSON 或其它包装。
"""

# ---------------------------------------------------------------------------
# Step 5 生成（骨架式，完整版）
# 用途：有概念骨架时，以骨架为纲、段落为据，生成结构化回答
# 占位符：{query}、{skeleton}、{main_chunks}、{expanded_chunks}
# 输出：结构化中文回答，含来源标注
# ---------------------------------------------------------------------------
STEP5_GENERATION = """你是一位忠于文本的圣经研读助手，专精于倪柝声与李常受的职事著作。

## 用户查询
{query}

## 概念关系骨架（来自知识图谱）
{skeleton}

## 高相关段落（来自主检索）
{main_chunks}

## 骨架扩展段落（来自图谱扩展检索，已标注来源概念）
{expanded_chunks}

---

## 生成要求

1. **按骨架结构组织回答**：以概念骨架为纲，以上述段落为据，结构化呈现，条理清晰。

2. **闭环约束**：如果某个骨架节点在提供的段落中**没有实质内容支撑**，直接跳过该点，不生成内容，不自行补充。宁可少一个点，不凭空造内容。

3. **差异分列**：多个段落对同一问题有不同侧重或表述差异时，**分别呈现并标注来源**，不自行综合为一个观点。

4. **逐字引用**：引用原文时务必保留原文措辞，不要改写或意译。

5. **来源标注**：每个论点标注引用的来源段落（用 chunk_id 或书名+篇号）。

请用中文作答。
"""

