async def main() -> None:
    import json
    from pathlib import Path

    rows: list[dict] = []
    for i, line in enumerate(_LINES, 1):
        stripped, sources = parse_source_from_line(line)
        ref_zh = format_source_zh(sources)
        has_star = bracket_has_star(ref_zh)

        print(f"\n{'='*72}")
        print(f"行{i}")
        print(f"中文正文: {stripped}")
        print(f"中文出处: {ref_zh}")
        print(f"出处条数: {len(sources)}  has_star={has_star}")

        src_rows: list[dict] = []
        for j, src in enumerate(sources, 1):
            dbg = await _kg_rag_source_lookup_debug(src)
            hit, _ = await _kg_rag_source_lookup(src)
            print(f"  [出处{j}] {src}")
            print(f"    查询词: {dbg.query}")
            print(f"    路1: {dbg.match_method} | en={dbg.source_en or '(空)'} | para={dbg.para_en or '-'}")
            print(f"    路1结果: {hit or '(空，将走路2)'}")
            src_rows.append({
                "zh": src,
                "query": dbg.query,
                "method": dbg.match_method,
                "en": hit or "",
            })

        full_en = await translate_source_zh(sources, [], has_star=has_star)
        print(f"  → 最终出处块(含路2): {full_en or '(空)'}")
        rows.append({
            "line": i,
            "body": stripped,
            "ref_zh": ref_zh,
            "n_sources": len(sources),
            "has_star": has_star,
            "sources": src_rows,
            "final": full_en,
        })

    print(f"\n{'='*72}")
    print(f"共 {len(_LINES)} 行")
    out_path = Path(__file__).resolve().parent / "_source_batch_result.json"
    out_path.write_text(json.dumps(rows, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"JSON: {out_path}")


if __name__ == "__main__":
    asyncio.run(main())
