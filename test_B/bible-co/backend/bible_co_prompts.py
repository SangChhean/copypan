def _build_cn_num() -> dict[str, int]:
    """生成中文数字 → 整数映射，覆盖 0（〇）与 1～150。"""
    digits = ["", "一", "二", "三", "四", "五", "六", "七", "八", "九"]
    result: dict[str, int] = {"〇": 0}
    for n in range(1, 151):
        if n < 10:
            result[digits[n]] = n
        elif n == 10:
            result["十"] = 10
        elif n < 20:
            result["十" + digits[n % 10]] = n
        elif n < 100:
            tens, ones = divmod(n, 10)
            if ones == 0:
                result[digits[tens] + "十"] = n
            else:
                result[digits[tens] + "十" + digits[ones]] = n
        else:
            hundreds = n // 100
            rest = n % 100
            prefix = digits[hundreds] + "百"
            if rest == 0:
                result[prefix] = n
            elif rest < 10:
                result[prefix + "零" + digits[rest]] = n
            elif rest == 10:
                result[prefix + "一十"] = n
            elif rest < 20:
                result[prefix + "一十" + digits[rest % 10]] = n
            else:
                tens, ones = divmod(rest, 10)
                if ones == 0:
                    result[prefix + digits[tens] + "十"] = n
                else:
                    result[prefix + digits[tens] + "十" + digits[ones]] = n
    return result


# 中文数字 → 整数（1～150，含〇=0）
