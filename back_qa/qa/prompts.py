# ---------------------------------------------------------------------------
# Step 1：概念抽取（Opus）
# 占位符：{question}、{concept_list}
# 输出：严格 JSON {"concepts": [...], "reasoning": "..."}
# concepts：1-5 个，必须来自词表
# ---------------------------------------------------------------------------
STEP1_CONCEPT_EXTRACTION = """你是一位深研圣经与职事文献的神学助手。

用户提问：
{question}

以下是职事信息概念词表（共 637 个概念）：
{concept_list}

请从上方词表中，识别出与该问题最相关的神学概念（1-5 个）。

要求：
1. 概念必须来自词表，不得自造
2. 数量 1-5 个，优先选最核心的
3. 只输出 JSON，不输出其他任何内容

输出格式：
{{"concepts": ["概念A", "概念B"], "reasoning": "简要说明选择理由"}}"""

# ---------------------------------------------------------------------------
# Step 3：相关性判断（Haiku）
# 占位符：{question}、{passages}
# 输出：严格 JSON {"relevant": true/false, "reason": "..."}
# ---------------------------------------------------------------------------
STEP3_RELEVANCE_CHECK = """你是一位职事信息相关性判断助手。

用户问题：
{question}

以下是从职事信息中检索到的段落：
{passages}

请判断：上述段落是否足以回答用户的问题？

判断标准：
- 段落中有与问题直接相关的内容 → relevant: true
- 段落内容与问题完全无关或严重不足 → relevant: false
- 有部分相关但不充分时，偏向 true（宁可尝试作答）

只输出 JSON，不输出其他任何内容：
{{"relevant": true, "reason": "简要说明"}}"""

# ---------------------------------------------------------------------------
# Step 4：答案生成（Sonnet，temp=0.3）
# 占位符：{question}、{passages}、{greek_context}、{verse_context}、{firewall_instruction}
# greek_context / verse_context / firewall_instruction 为空时传空串即可
# ---------------------------------------------------------------------------
STEP4_ANSWER_GENERATION = """你是一位职事信息问答助手，严格基于所提供的职事信息段落归纳作答。

用户问题：
{question}
{greek_context}{verse_context}
以下是相关职事信息段落：
{passages}
{firewall_instruction}
作答要求：
1. 严格基于上方段落归纳，不编造、不改写
2. 用自然语言段落呈现，条理清晰
3. 若段落中自然出现希腊／希伯来原文，可在答案中适当标注，如：生命（ζωή）
4. 若段落中有关键经文，可自然引用，如：弗一10
5. 答案末尾附引用书目列表，格式如下：

【引用书目】
· 《书名》

只输出答案正文与引用书目，不输出其他内容。"""

